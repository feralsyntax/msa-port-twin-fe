import { getDataProvenance } from '../../../utils/dataProvenance';
import type { ProvenanceContext } from '../../../utils/dataProvenance';
import './ProvenanceBadge.scss';

interface ProvenanceBadgeProps {
  value: unknown;
  context?: ProvenanceContext;
}

const provenanceLabels = {
  measured: {
    label: 'Measured',
    description: 'Directly observed data from an instrument or telemetry feed.',
  },
  historical: {
    label: 'Historical',
    description: 'Previously recorded or externally sourced data, not a live observation.',
  },
  'ai-estimate': {
    label: 'AI estimate',
    description: 'An estimate generated by an AI model; it is not a verified observation.',
  },
  simulated: {
    label: 'Simulated',
    description: 'Synthetic, simulated, or demonstration data.',
  },
} as const;

const unknownLabel = {
  label: 'Unknown',
  description: "The backend did not identify this data's provenance.",
};

const ProvenanceBadge = ({ value, context }: ProvenanceBadgeProps) => {
  const provenance = getDataProvenance(value, context);
  const content = provenance ? provenanceLabels[provenance] : unknownLabel;
  const variant = provenance ?? 'unknown';

  return (
    <span
      className={`provenance-badge provenance-badge--${variant}`}
      title={content.description}
      aria-label={`${content.label} provenance. ${content.description}`}
    >
      {content.label}
    </span>
  );
};

export default ProvenanceBadge;
